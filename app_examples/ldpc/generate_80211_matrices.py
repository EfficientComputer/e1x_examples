H = np.fromstring(H, dtype=int, sep=" ")
H = H.reshape((336, 8))

H_dense = np.zeros((336, 672), dtype=int)
for i in range(336):
    for j in range(8):
        if H[i][j]:
            nz_idx = H[i][j] - 1
            H_dense[i][nz_idx] = 1

# Next, derive G from H. Here's a simple explanation on how
# it can be done: https://stackoverflow.com/questions/43887951/how-to-determine-ldpc-generator-matrix-from-parity-check-matrix-802-16e

A = H_dense[0:336, 0:336]
B = H_dense[0:336, 336:]

AT = A.T
BinvT = np.linalg.inv(B).T

# make sure the result is in GF(2)
G_dense = np.concat([np.eye(336, dtype=int), AT @ BinvT], axis=1) % 2

res = (G_dense @ H_dense.T) % 2

# verify that generator matrix is correct
assert np.allclose(res, np.zeros((336, 336), dtype=int))

# store H and G in sparse forms
H_sparse = []
G_sparse = []
H_nz_counter = 0
G_nz_counter = 0
for i in range(336):
    for j in range(672):
        if H_dense[i][j]:
            H_sparse.append((i, j, H_nz_counter))
            H_nz_counter += 1
        if G_dense[i][j]:
            G_sparse.append((i, j, G_nz_counter))
            G_nz_counter += 1


def get_csr_view(nz_coords, n_ptrs, is_row_csr):
    nnz = len(nz_coords)
    ptrs = np.zeros(n_ptrs + 1, dtype=int)
    ids = np.zeros(nnz, dtype=int)
    nz_ids = np.zeros(nnz, dtype=int)

    nz_coords_copy = nz_coords.copy()
    if is_row_csr:
        nz_coords_copy.sort(key=lambda x: x[0])
    else:
        nz_coords_copy.sort(key=lambda x: x[1])

    nz_idx = 0
    last_offset = 0
    nz = nz_coords_copy[nz_idx]
    ptr_idx = nz[0] if is_row_csr else nz[1]

    ptrs[0] = 0
    for i in range(n_ptrs):
        n = 0
        while ptr_idx == i:
            n += 1
            ids[nz_idx] = nz[1] if is_row_csr else nz[0]
            nz_ids[nz_idx] = nz[2]
            if nz_idx >= nnz - 1:
                break

            nz_idx += 1
            nz = nz_coords_copy[nz_idx]
            ptr_idx = nz[0] if is_row_csr else nz[1]

        last_offset += n
        ptrs[i + 1] = last_offset

    return ptrs, ids, nz_ids

